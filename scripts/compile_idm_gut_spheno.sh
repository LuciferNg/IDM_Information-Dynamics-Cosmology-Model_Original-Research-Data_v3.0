#!/bin/bash
# compile_idm_gut_spheno.sh — Compile SPheno for OAS IDM_GUT model
# Run after MakeSPheno[] completes in Wolfram Engine

SPHENO_DIR="/tmp/SPheno-4.0.5"
MODEL_DIR="${SPHENO_DIR}/IDM_GUT"
SARAH_OUTPUT="$HOME/.WolframEngine/Applications/SARAH/Output/IDM_GUT/EWSB/SPheno"

echo "=== Compiling OAS IDM_GUT SPheno ==="
echo "Source: ${SARAH_OUTPUT}"

# Verify output exists
if [ ! -d "${SARAH_OUTPUT}" ]; then
    echo "ERROR: SARAH output not found at ${SARAH_OUTPUT}"
    echo "Run MakeSPheno[] in Wolfram Engine first"
    exit 1
fi

# Create model directory in SPheno
mkdir -p "${MODEL_DIR}"

# Copy SARAH-generated Fortran files
echo "Copying Fortran files..."
cp -v "${SARAH_OUTPUT}"/*.f90 "${MODEL_DIR}/" 2>/dev/null
cp -rv "${SARAH_OUTPUT}/TwoLoopMasses" "${MODEL_DIR}/" 2>/dev/null

# Create Makefile for IDM_GUT model
cat > "${MODEL_DIR}/Makefile" << 'MAKEEOF'
# Makefile for OAS IDM_GUT SPheno model
# Generated by SARAH 4.15.5 / Hermes Agent

FC = gfortran
FFLAGS = -O3 -fPIC -ffixed-line-length-none -fopenmp
LDFLAGS = -O3 -fopenmp

SRCS = $(wildcard *.f90)
OBJS = $(SRCS:.f90=.o)

SPheno_IDM_GUT: $(OBJS)
	$(FC) $(LDFLAGS) -o $@ $(OBJS) -lblas -llapack

%.o: %.f90
	$(FC) $(FFLAGS) -c $< -o $@

clean:
	rm -f *.o SPheno_IDM_GUT

.PHONY: clean
MAKEEOF

# Also create LesHouches input file
cat > "${SPHENO_DIR}/input/LesHouches.in.IDM_GUT" << 'LESEOF'
Block MODSEL
    1   0     # mSUGRA
Block SMINPUTS
    1   1.27934000E+02   # M_Z
    2   1.16637000E-05   # G_F
    3   1.18000000E-01   # alpha_s(M_Z)
    4   9.11876000E+01   # m_b(m_b)
    5   1.77700000E+00   # m_tau
    6   1.72800000E+02   # m_t
    7   8.00000000E-01   # m_tau
Block MINPAR
    1   1.00000000E+03   # m0
    2   1.00000000E+03   # m12
    3   1.00000000E+01   # tanβ
    4   1                # sign(μ)
    5  -1.50000000E+03   # A0
Block EXTPAR
    0   1.00000000E+03   # Q = 1 TeV
LESEOF

# Compile
echo "Compiling..."
cd "${MODEL_DIR}" && make -j$(nproc) 2>&1

if [ -f "${MODEL_DIR}/SPheno_IDM_GUT" ]; then
    echo "✅ Compilation successful!"
    echo "Binary: ${MODEL_DIR}/SPheno_IDM_GUT"
else
    echo "❌ Compilation failed"
    echo "Check error messages above"
fi